// Mutation check. Each row breaks ONE behaviour in ONE source file, runs the whole
// suite, and requires it to FAIL. A test that a mutation cannot fail is a test that
// cannot fail.
//
//   node tools/mutations.mjs              every mutation must be caught
//   node tools/mutations.mjs --coverage   ALSO list every test that NO mutation makes fail
//                                         (a test with no demonstrated teeth);
//                                         add --strict to exit 1 if there is any
//
// A row is REJECTED (and the run fails) if it is not a real behavioural mutation:
//   - its find text must be present, and the replacement must change something;
//   - a mutated .js/.mjs file must still PARSE (a syntax error makes every test fail
//     trivially); index.template.html rows skip this check;
//   - no test FILE may fail to load (same reason);
//   - it may fail at most MAX_FAILING tests (a blunt mutation that breaks everything covers
//     every test and proves nothing). A row may carry an own limit as a fifth element, { max: N },
//     but only where the mutated thing (the minus sign) is genuinely used by that many tests.
// A row's file is a src/ file name (JavaScript, index.template.html or styles.css), or
// 'build.js'. The rows cover the distributed-load beam's behaviours: physics (equivalent
// forces and locations, slider snapping), format (minus sign, -0, off-the-beam notes), state
// (the store), presets (URL parameters), layout (figure geometry, fixed force scale), scene
// (the SVG: classes, text size, arrow heads), panel (the worked calculation), controls (slider
// and peak-button wiring), app (page wiring) and build (the single-scope bundler).
//
// The run works on a TEMPORARY COPY (src/, test/, tools/, build.js and package.json copied into the
// system temp directory). The real repository is never written, so an interrupted run
// (Ctrl-C) cannot leave a mutated source behind. The copy is removed at the end and on
// SIGINT / SIGTERM. The whole suite runs once per row (a few seconds each).
